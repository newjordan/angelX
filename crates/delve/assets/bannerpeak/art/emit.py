#!/usr/bin/env python3
"""Ink every frame and write src/render/overworld/arena/bannerpeak/art_data.rs.

    python3 emit.py

Frames are cropped to their ink and carry their offset from the anchor (the
bottom centre of the box the rules give the body), so the stage stamps them at
the feet. Seat tones are the digits 1 2 3 4; the stage swaps them per seat.
"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import knight_art as K
import foe_art as F

OUT = Path(__file__).resolve().parents[3] / "src/render/overworld/arena/bannerpeak/art_data.rs"


def crop(s, ax, ay):
    # nothing under the feet: the ground is drawn by the tiles
    s = {p: c for p, c in s.items() if p[1] < ay}
    xs = [x for x, _ in s]
    ys = [y for _, y in s]
    x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
    rows = []
    for y in range(y0, y1 + 1):
        rows.append("".join(s.get((x, y), ".") for x in range(x0, x1 + 1)))
    return x0 - ax, y0 - ay, rows


def emit_set(name, frames, ax, ay):
    out = [f"pub const {name}: &[Set] = &["]
    for key, seq in frames.items():
        out.append(f'    Set {{ name: "{key}", frames: &[')
        for s in seq:
            dx, dy, rows = crop(s, ax, ay)
            body = ", ".join(f'"{r}"' for r in rows)
            out.append(f"        Frame {{ dx: {dx}, dy: {dy}, rows: &[{body}] }},")
        out.append("    ] },")
    out.append("];")
    return "\n".join(out)


def main():
    parts = [
        "//! Generated by assets/bannerpeak/art/emit.py from the hand-inked parts in knight_art.py and",
        "//! foe_art.py. Do not edit here: change the art and run the script again.",
        "//!",
        "//! Each frame is cropped to its ink and carries its offset (dx, dy) from the anchor: the bottom",
        "//! centre of the body's box. Inks are the realm's; the digits 1 2 3 4 are the seat's four tones.",
        "",
        "pub struct Frame {",
        "    pub dx: i8,",
        "    pub dy: i8,",
        "    pub rows: &'static [&'static str],",
        "}",
        "",
        "pub struct Set {",
        "    pub name: &'static str,",
        "    pub frames: &'static [Frame],",
        "}",
        "",
        "/// The small knight, anchored at the bottom centre of its 12 by 20 box.",
        emit_set("SMALL", K.knight_frames(False), 12, 28),
        "",
        "/// The big knight (and the flame knight), anchored at the bottom centre of its 14 by 30 box.",
        emit_set("BIG", K.knight_frames(True), 12, 38),
        "",
        "/// The foes and the loaf, anchored at the feet.",
        emit_set("FOES", F.frames(), 10, 16),
        "",
    ]
    OUT.write_text("\n".join(parts))
    print("wrote", OUT, OUT.stat().st_size)


main()
