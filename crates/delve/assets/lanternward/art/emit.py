#!/usr/bin/env python3
"""Ink every Lanternward frame and write
src/render/overworld/arena/lanternward/art_data.rs.

    python3 emit.py

Frames are cropped to their ink and carry their offset from the slot's
top-left corner; the bank pads them back to the slot's size. Inks are the
realm's, so a character here is the colour the stage draws.
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import warden as W
import snuffer as S
import turret as T
import props as P

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "src/render/overworld/arena/lanternward/art_data.rs"
SLOTS = json.loads((ROOT / "assets/lanternward/slots.json").read_text())


def crop(sp):
    px = {p: c for p, c in sp.px.items() if 0 <= p[0] < sp.w and 0 <= p[1] < sp.h}
    if not px:
        return 0, 0, [""]
    xs = [x for x, _ in px]
    ys = [y for _, y in px]
    x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
    rows = ["".join(px.get((x, y), ".") for x in range(x0, x1 + 1)) for y in range(y0, y1 + 1)]
    return x0, y0, rows


def sets():
    everything = {"warden": W.frames(), "snuffer": S.frames(), "turret": T.frames()}
    for slot, states in P.all_props().items():
        everything[slot] = states
    return everything


def main():
    everything = sets()
    out = [
        "//! Generated by assets/lanternward/art/emit.py from the hand-inked parts beside it. Do not edit",
        "//! here: change the art and run the script again.",
        "//!",
        "//! Each frame is cropped to its ink and carries its offset (x, y) from its slot's top-left corner.",
        "//! Inks are the realm's (`render/overworld/ink.rs`).",
        "",
        "pub struct Frame {",
        "    pub x: u8,",
        "    pub y: u8,",
        "    pub rows: &'static [&'static str],",
        "}",
        "",
        "pub struct Set {",
        "    pub slot: &'static str,",
        "    pub state: &'static str,",
        "    pub frames: &'static [Frame],",
        "}",
        "",
        "pub const SETS: &[Set] = &[",
    ]
    by_id = {s["id"].split(".", 1)[1]: s for s in SLOTS}
    total = 0
    for slot, states in everything.items():
        spec = by_id[slot]
        for state, frames in states.items():
            want = len(spec["states"][state])
            assert len(frames) == want, f"{slot}.{state}: {len(frames)} frames, slot wants {want}"
            for f in frames:
                assert (f.w, f.h) == tuple(spec["size"]), f"{slot}.{state} is {f.w}x{f.h}, slot is {spec['size']}"
            out.append(f'    Set {{ slot: "{slot}", state: "{state}", frames: &[')
            for f in frames:
                x, y, rows = crop(f)
                body = ", ".join(f'"{r}"' for r in rows)
                out.append(f"        Frame {{ x: {x}, y: {y}, rows: &[{body}] }},")
                total += 1
            out.append("    ] },")
        missing = set(spec["states"]) - set(states)
        assert not missing, f"{slot} lacks {missing}"
    out.append("];")
    OUT.write_text("\n".join(out) + "\n")
    print("wrote", OUT, OUT.stat().st_size, "bytes,", total, "frames")


main()
