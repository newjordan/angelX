#!/usr/bin/env python3
"""Ink every Moonfall figure and write
src/render/overworld/arena/moonfall/art_data.rs.

    python3 emit.py

Frames are cropped to their ink and carry their offset (x, y) from the slot's
top-left corner. Inks are the realm's (`render/overworld/ink.rs`); the knights'
house colour is drawn in `#` `&` `*` and swapped for the seat's ramp by the
bank.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import people as P
import knight as K
import wisp as WS
import aster as A
import items as I
from rig import mirrored

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "src/render/overworld/arena/moonfall/art_data.rs"


def crop(sp):
    px = {p: c for p, c in sp.px.items() if 0 <= p[0] < sp.w and 0 <= p[1] < sp.h}
    xs = [x for x, _ in px]
    ys = [y for _, y in px]
    x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
    rows = ["".join(px.get((x, y), ".") for x in range(x0, x1 + 1)) for y in range(y0, y1 + 1)]
    return x0, y0, rows


def folk_sets():
    out = []
    for name, c in P.PEOPLE.items():
        for d, key in (("down", "down"), ("up", "up"), ("left", "left")):
            idle = []
            for ph in range(4):
                x = {"bob": [0, -1, 0, -1][ph], "blink": ph == 2, "t": ph}
                idle.append(P.person(c, d, "idle", ph, x=x).finish())
            walk = [P.person(c, d, "walk", ph, x={"t": ph}).finish() for ph in range(4)]
            out.append((name, f"idle-{key}", [14, 14, 14, 14], idle))
            out.append((name, f"walk-{key}", [6, 6, 6, 6], walk))
            if d == "left":
                out.append((name, "idle-right", [14, 14, 14, 14], [mirrored(s) for s in idle]))
                out.append((name, "walk-right", [6, 6, 6, 6], [mirrored(s) for s in walk]))
        for state, f in P.WORK.get(name, {}).items():
            n = P.WORK_FRAMES[name][state]
            out.append((name, state, [8] * n if state != "light" else [8, 10, 12], [f(ph).finish() for ph in range(n)]))
    return out


def knight_sets():
    out = []
    for m in K.MASKS:
        slot = f"knight-{m}"
        for d in ("down", "up", "left"):
            idle = [K.idle(m, d, ph).finish() for ph in range(4)]
            walk = [K.walk(m, d, ph).finish() for ph in range(4)]
            out.append((slot, f"idle-{d}", [16, 16, 16, 16], idle))
            out.append((slot, f"walk-{d}", [5, 5, 5, 5], walk))
            if d == "left":
                out.append((slot, "idle-right", [16, 16, 16, 16], [mirrored(s) for s in idle]))
                out.append((slot, "walk-right", [5, 5, 5, 5], [mirrored(s) for s in walk]))
        for d in ("down", "up", "left"):
            roll = [K.roll(m, d, ph).finish() for ph in range(3)]
            out.append((slot, f"roll-{d}", [2, 2, 2], roll))
            if d == "left":
                out.append((slot, "roll-right", [2, 2, 2], [mirrored(s) for s in roll]))
        out.append((slot, "cheer", [7, 7], [K.cheer(m, ph).finish() for ph in range(2)]))
        out.append((slot, "down", [12, 12], [K.down(m, ph).finish() for ph in range(2)]))
    return out


def other_sets():
    out = []
    w = WS.frames()
    out.append(("wisp", "drift", [6, 6, 6, 6], [s.finish() for s in w["drift"]]))
    out.append(("wisp", "snuff", [4] * 6, [s.finish() for s in w["snuff"]]))
    out.append(("wisp", "shy", [5, 5], [s.finish() for s in w["shy"]]))
    a = A.frames()
    for state, dur in (("idle", [20, 20]), ("ride", [6, 6, 6, 6]), ("lame", [14, 14])):
        fr = [s.finish() for s in a[state]]
        out.append(("aster", f"{state}-left", dur, fr))
        out.append(("aster", f"{state}-right", dur, [mirrored(s) for s in fr]))
    for name, sp in I.all_items().items():
        out.append((name, "idle", [12], [sp]))
    return out


def main():
    sets = folk_sets() + knight_sets() + other_sets()
    out = [
        "//! Generated by assets/moonfall/art/emit.py from the hand-inked parts beside it. Do not edit",
        "//! here: change the art and run the script again.",
        "//!",
        "//! Each frame is cropped to its ink and carries its offset (x, y) from its slot's top-left corner.",
        "//! Inks are the realm's (`render/overworld/ink.rs`); `#` `&` `*` are a knight's house colour",
        "//! (shadow, base, light), swapped for the seat's own by the bank.",
        "",
        "pub struct Frame {",
        "    pub x: u8,",
        "    pub y: u8,",
        "    pub rows: &'static [&'static str],",
        "}",
        "",
        "pub struct Set {",
        "    pub slot: &'static str,",
        "    pub state: &'static str,",
        "    pub size: (u8, u8),",
        "    pub ticks: &'static [u32],",
        "    pub frames: &'static [Frame],",
        "}",
        "",
        "pub const SETS: &[Set] = &[",
    ]
    total = 0
    for slot, state, ticks, frames in sets:
        assert len(ticks) == len(frames), (slot, state)
        w, h = frames[0].w, frames[0].h
        tk = ", ".join(str(t) for t in ticks)
        out.append(f'    Set {{ slot: "{slot}", state: "{state}", size: ({w}, {h}), ticks: &[{tk}], frames: &[')
        for f in frames:
            x, y, rows = crop(f)
            body = ", ".join(f'"{r}"' for r in rows)
            out.append(f"        Frame {{ x: {x}, y: {y}, rows: &[{body}] }},")
            total += 1
        out.append("    ] },")
    out.append("];")
    OUT.write_text("\n".join(out) + "\n")
    print("wrote", OUT, OUT.stat().st_size, "bytes,", total, "frames in", len(sets), "sets")


main()
