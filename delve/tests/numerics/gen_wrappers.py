def wrapper(name, body):
    return f"def case.{name}(+input: J.Val) -> J.Val:\n  {body}\n"


def main():
    parts = [HEAD]
    for mod, table in (("W", W), ("RS", RS), ("RS", DBL)):
        for fn, sig in table.items():
            args, ret = sig.split(":")
            call = f"{mod}.{fn}(" + ", ".join(IN[k].format(i=i) for i, k in enumerate(args)) + ")"
            parts.append(wrapper(f"{mod}.{fn}", OUTK[ret].format(e=call)))
    for name, body in EXTRA.items():
        parts.append(wrapper(name, body))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(parts))
    print(f"{OUT}: {len(W) + len(RS) + len(DBL) + len(EXTRA)} wrappers")


if __name__ == "__main__":
    main()
