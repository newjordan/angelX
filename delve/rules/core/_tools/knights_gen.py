#!/usr/bin/env python3
"""knights_gen: knights::COMPANY as Bend (delve/rules/core/knights_data.bend), from the Rust source."""
import pathlib, re, json
root = pathlib.Path(__file__).resolve().parents[4]
text = (root / "crates/delve/src/rules/knights.rs").read_text()
body = text[text.index("pub const COMPANY"):text.index("];\n\npub fn knight")]
entries = re.findall(r"Knight \{(.*?)\n    \},", body, re.S)
def s(key, e):
    m = re.search(r"\b%s:\s*\"((?:[^\"\\]|\\.)*)\"" % key, e)
    return m.group(1)
def lst(key, e):
    m = re.search(r"\b%s:\s*&\[(.*?)\]," % key, e, re.S)
    return re.findall(r"\"((?:[^\"\\]|\\.)*)\"", m.group(1))
def num(key, e):
    return int(re.search(r"\b%s:\s*(\d+)" % key, e).group(1))
def cols(e):
    m = re.search(r"colours:\s*&\[(.*?)\],\s*$", e, re.S | re.M)
    return re.findall(r"\('(.)',\s*'(.)'\)", m.group(1))
def q(x):
    return json.dumps(x, ensure_ascii=False)
ks = []
for e in entries:
    ks.append(dict(id=s("id", e), name=s("name", e), title=s("title", e), about=s("about", e), arm=s("arm", e),
                   guard=s("guard", e), hand=lst("hand", e), spells=lst("spells", e), bombs=num("bombs", e),
                   max_hp=num("max_hp", e), colours=cols(e)))
out = ["# GENERATED by _tools/knights_gen.py from knights.rs (knights::COMPANY). Do not edit.", ""]
def jv(v):
    if isinstance(v, str):
        return "J.JS{%s}" % q(v)
    if isinstance(v, int):
        return "J.JU{%d}" % v
    if isinstance(v, list):
        return "J.JA{[%s]}" % ", ".join(jv(x) for x in v)
    if isinstance(v, tuple):
        return "J.JA{[J.JS{%s}, J.JS{%s}]}" % (q(v[0]), q(v[1]))
for i, k in enumerate(ks):
    obj = "J.obj()"
    for f in ("id", "name", "title", "about", "arm", "guard", "hand", "spells", "bombs", "max_hp", "colours"):
        obj = "J.set(%s, %s, %s)" % (obj, q(f), jv(k[f]))
    out.append("def knights.company.k%d() -> J.Val:\n  %s\n" % (i, obj))
out.append("def knights.company.len() -> U32:\n  %d\n" % len(ks))
out.append("def knights.company(i: U32) -> J.Val:")
out.append("  match i:")
for i in range(len(ks)):
    out.append("    case %d:\n      knights.company.k%d()" % (i, i))
out.append("    case _:\n      J.JNull{}")
(root / "delve/rules/core/knights_data.bend").write_text("\n".join(out) + "\n")
print(len(ks), "knights")
