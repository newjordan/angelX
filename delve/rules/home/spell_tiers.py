#!/usr/bin/env python3
"""Writes delve/rules/home/_spell_tiers.bend from TIERS in crates/delve/src/rules/spell_upgrades.rs."""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[3]
SRC = (ROOT / "crates/delve/src/rules/spell_upgrades.rs").read_text()
body = SRC[SRC.index("const TIERS: [Step; 3] = ["):SRC.index("impl Hero {")]
steps = re.findall(r"Step \{(.*?)\n    \},", body, re.S)
assert len(steps) == 3, len(steps)
out = ["# Generated by spell_tiers.py from TIERS in crates/delve/src/rules/spell_upgrades.rs.", ""]
for kind in ("power", "wait"):
    out.append(f"# The {kind} of a spell's number at tiers I, II, III (index = the card's number, 0 to 120).")
    out.append(f"def spell_upgrades.TIER_{kind.upper()}(+tier: U32) -> List<&2, U32>:")
    rows = []
    for s in steps:
        m = re.search(kind + r": \[(.*?)\]", s, re.S)
        rows.append([int(x) for x in re.findall(r"\d+", m.group(1))])
    for r in rows:
        assert len(r) == 121, len(r)
    out.append("  Bool.pick(List<&2, U32>, U32.is_eq(tier, 0), [" + ", ".join(map(str, rows[0])) + "],")
    out.append("    Bool.pick(List<&2, U32>, U32.is_eq(tier, 1), [" + ", ".join(map(str, rows[1])) + "],")
    out.append("      [" + ", ".join(map(str, rows[2])) + "]))")
    out.append("")
# The numbers beside the tables, as the Step J value.
fields = ["warden_hp", "rip_reach", "hammer_burst", "slam_reach", "fury", "rot", "rot_reach", "haul_reach", "quick_reach", "quick_life", "elixir_reach", "cabbage_extra", "imposture"]
out.append("# The step's other numbers, as the Step the Rust holds (power and wait aside).")
out.append("def spell_upgrades.step(+tier: U32) -> J.Val:")
vals = []
for s in steps:
    row = {}
    for f in fields:
        m = re.search(r"\b" + f + r": ([^,\n]+),", s)
        v = m.group(1).strip()
        row[f] = v
    vals.append(row)
def lit(f, v):
    if v == "spells::IMPOSTURE_TICKS":
        return "J.JU{150}"
    if "." in v:
        return "J.JF{%s}" % v
    return "J.JU{%s}" % v
def obj(row):
    return "home.util.obj([" + ", ".join('("%s", %s)' % (f, lit(f, row[f])) for f in fields) + "])"
out.append("  Bool.pick(J.Val, U32.is_eq(tier, 0), " + obj(vals[0]) + ",")
out.append("    Bool.pick(J.Val, U32.is_eq(tier, 1), " + obj(vals[1]) + ",")
out.append("      " + obj(vals[2]) + "))")
(ROOT / "delve/rules/home/_spell_tiers.bend").write_text("\n".join(out) + "\n")
print("ok")
