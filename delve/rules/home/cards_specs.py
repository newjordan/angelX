#!/usr/bin/env python3
"""Writes delve/rules/home/_cards_specs.bend from SPECS in crates/delve/src/rules/cards.rs.

The effect vocabulary of the card checker: one row per `Spec` (word, the effect's
serde name, its bounds, whether a held card may carry it, whether a spent one may).
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[3]
SRC = (ROOT / "crates/delve/src/rules/cards.rs").read_text()
body = SRC[SRC.index("const SPECS: &[Spec] = &["):]
body = body[: body.index("\n];")]
const = {"VOLLEY_FLOOR": 5}


def snake(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


rows = []
for m in re.finditer(
    r'Spec \{\s*word: "(\w+)",\s*low: (\w+),\s*high: (\w+),\s*cap: (\w+),\s*hold: (\w+),\s*spend: (\w+),\s*make: Effect::(\w+),',
    body,
):
    word, low, high, cap, hold, spend, make = m.groups()
    n = lambda v: const.get(v, None) if not v.isdigit() else int(v)
    rows.append((word, snake(make), n(low), n(high), n(cap), hold == "true", spend == "true"))

out = ["# Generated by cards_specs.py from SPECS in crates/delve/src/rules/cards.rs.", "",
       "type CardsSpec is Data:",
       "  CardsSpec{word: String, name: String, low: U32, high: U32, cap: U32, hold: Bool, spend: Bool}", "",
       "def cards.SPECS() -> List<&2, CardsSpec>:", "  ["]
for i, (w, nm, lo, hi, cap, hold, spend) in enumerate(rows):
    out.append(f'    CardsSpec{{"{w}", "{nm}", {lo}, {hi}, {cap}, {"True{}" if hold else "False{}"}, {"True{}" if spend else "False{}"}}}' + ("," if i + 1 < len(rows) else ""))
out.append("  ]")
(ROOT / "delve/rules/home/_cards_specs.bend").write_text("\n".join(out) + "\n")
print(len(rows), "specs")
