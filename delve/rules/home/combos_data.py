#!/usr/bin/env python3
"""Writes delve/rules/home/_combos_data.bend from the family tables of crates/delve/src/rules/combos.rs."""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[3]
SRC = (ROOT / "crates/delve/src/rules/combos.rs").read_text()
names = re.findall(r'Family::(\w+) => "(\w+)",', SRC[SRC.index("pub fn word"):SRC.index("pub fn words")])
words_src = SRC[SRC.index("pub fn words"):SRC.index("/// A super effect")]
fams = []
for m in re.finditer(r"Family::(\w+) => &\[(.*?)\],\n", words_src, re.S):
    fams.append((m.group(1), re.findall(r'"([\w]+)"', m.group(2))))
order = re.findall(r"Family::(\w+),", SRC[SRC.index("pub const ALL"):SRC.index("pub fn word")])
idx = {n: i for i, n in enumerate(order)}
rec = re.findall(r'Recipe \{ effect: "(\w+)", name: "([^"]+)", needs: \[Family::(\w+), Family::(\w+)\] \}', SRC)
out = ["# Generated by combos_data.py from crates/delve/src/rules/combos.rs.", ""]
out.append("# The family names, in `Family::ALL` order (the order a BTreeSet<Family> iterates).")
out.append("def combos.NAMES() -> List<&2, String>:")
out.append("  [" + ", ".join('"%s"' % dict(names)[n] for n in order) + "]")
out.append("")
out.append("# The words in a wish's name or scroll that make it of each family, by family index.")
out.append("def combos.WORDS() -> List<&2, List<&2, String>>:")
fw = dict(fams)
out.append("  [" + ",\n   ".join("[" + ", ".join('"%s"' % w for w in fw[n]) + "]" for n in order) + "]")
out.append("")
out.append("# The super effects: (effect word, name, first family, second family).")
out.append("def combos.RECIPES() -> List<&2, List<&2, String>>:")
out.append("  [" + ",\n   ".join('["%s", "%s", "%d", "%d"]' % (e, n, idx[a], idx[b]) for e, n, a, b in rec) + "]")
(ROOT / "delve/rules/home/_combos_data.bend").write_text("\n".join(out) + "\n")
print(len(order), "families", len(rec), "recipes")
