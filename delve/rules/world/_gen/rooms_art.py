#!/usr/bin/env python3
"""Writes ../rooms_art.bend: the dungeon masters' drawn rooms, from
cockpit/live/rooms-rules/rooms-art.json (the module's captured answers)."""
import json, pathlib
HERE = pathlib.Path(__file__).resolve().parent
art = json.loads((HERE.parents[3] / "cockpit/live/rooms-rules/rooms-art.json").read_text())

def quads(answer):
    return "[" + ", ".join("[" + ", ".join(f'"{r}"' for r in q["rows"]) + "]" for q in answer["quads"]) + "]"

T = "List<&2, List<&2, String>>"
out = ["# generated by _gen/rooms_art.py from cockpit/live/rooms-rules/rooms-art.json.",
       "# Each answer is a list of quadrants, each a list of row strings (`.` floor, `#` block, `~` hazard).", ""]
c = art["consts"]
out += ["# The quadrant sizes of the bigger rooms, the authored share (percent) and the least floor.",
        "def layout.rooms.sizes() -> List<&2, Sigma<&2, &2, U32, _ => U32>>:",
        "  [" + ", ".join(f"({w}, {h})" for w, h in c["sizes"]) + "]", "",
        "def layout.rooms.authored_share() -> U32:", f"  {c['share']}", "",
        "def layout.rooms.least_floor() -> U32:", f"  {c['least_floor']}", ""]
for p in range(7):
    out += [f"def layout.rooms.small.p{p}() -> {T}:", f"  {quads(art['small'][str(p)])}", ""]
out += [f"def layout.rooms.small(+pack: U32) -> {T}:", "  layout.rooms.small.n0(pack)", ""]
for p in range(7):
    nxt = f"layout.rooms.small.n{p + 1}(pack)" if p < 6 else "[]"
    out += [f"def layout.rooms.small.n{p}(+pack: U32) -> {T}:", f"  layout.rooms.small.m{p}(U32.is_eq(pack, {p}), pack)", "",
            f"def layout.rooms.small.m{p}(hit: Bool, +pack: U32) -> {T}:", "  match hit:", "    case True{}:", f"      layout.rooms.small.p{p}()", "    case False{}:", f"      {nxt}", ""]
# sized
keys = []
for k, v in art["sized"].items():
    p, w, h = (int(x) for x in k.split(","))
    keys.append((p, w, h, v))
for p, w, h, v in keys:
    out += [f"def layout.rooms.sized.p{p}w{w}h{h}() -> {T}:", f"  {quads(v)}", ""]
out += [f"def layout.rooms.great(+pack: U32, +w: U32, +h: U32) -> {T}:", "  layout.rooms.great.n0(pack, w, h)", ""]
for i, (p, w, h, v) in enumerate(keys):
    nxt = f"layout.rooms.great.n{i + 1}(pack, w, h)" if i + 1 < len(keys) else "[]"
    out += [f"def layout.rooms.great.n{i}(+pack: U32, +w: U32, +h: U32) -> {T}:",
            f"  layout.rooms.great.m{i}(Bool.and(U32.is_eq(pack, {p}), Bool.and(U32.is_eq(w, {w}), U32.is_eq(h, {h}))), pack, w, h)", "",
            f"def layout.rooms.great.m{i}(hit: Bool, +pack: U32, +w: U32, +h: U32) -> {T}:",
            "  match hit:", "    case True{}:", f"      layout.rooms.sized.p{p}w{w}h{h}()", "    case False{}:", f"      {nxt}", ""]
(HERE.parent / "rooms_art.bend").write_text("\n".join(out) + "\n")
print("rooms_art.bend", len(out), "lines")
