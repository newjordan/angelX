#!/usr/bin/env python3
"""Writes ../pack_data.bx: the packs' rosters and room templates, copied from
crates/delve/src/rules/layout.rs (rosters and TEMPLATE consts)."""
import re, pathlib
HERE = pathlib.Path(__file__).resolve().parent
src = (HERE.parents[3] / "crates/delve/src/rules/layout.rs").read_text()

def snake(n):
    return re.sub(r'(?<!^)(?=[A-Z])', '_', n).lower()

i = src.index("pub fn roster_at"); j = src.index("/// How many dangerous kinds")
body = src[i:j]
arm = re.compile(r"\(Pack::(\w+), ([0-9 |_]+)\) => &\[(.*?)\],\n", re.S)
arms = [(m.group(1), m.group(2).strip(), re.findall(r"\((\w+), (\d+)\)", m.group(3))) for m in arm.finditer(body)]

out = ["# generated by _gen/pack_data.py from rules/layout.rs: the packs' rosters and templates.",
       "# Enemy kinds are their serde names; a roster is (kind, weight) in Rust's order.", ""]
names = {}
for pack, depths, items in arms:
    key = snake(pack) + "_" + {"0 | 1": "early", "_": "late", "2": "mid"}[depths]
    if pack in ("Hellforge", "Archive", "Fungal", "Unknown"):
        key = snake(pack)
    names[(pack, depths)] = key
    rows = ", ".join(f'("{snake(k)}", {w})' for k, w in items)
    out += [f"def layout.roster.{key}() -> List<&2, Sigma<&2, &2, String, _ => U32>>:", f"  [{rows}]", ""]

def branch(pack):
    return [(d, names[(p, d)]) for p, d, _ in arms if p == pack]

out += ["# Who lives on a floor of this pack (`roster_at`).",
        "def layout.Pack.roster_at(+pack: String, +depth: U32) -> List<&2, Sigma<&2, &2, String, _ => U32>>:"]
packs = ["Crypt", "Cavern", "Hellforge", "Archive", "Fungal", "Swamp", "Unknown"]
ind = "  "
for n, pack in enumerate(packs):
    last = n == len(packs) - 1
    br = branch(pack)
    cond = f'String.eq(pack, "{snake(pack)}")'
    if not last:
        out.append(f"{ind}if {cond}:")
    inner = ind + ("  " if not last else "")
    if len(br) == 1:
        out.append(f"{inner}layout.roster.{br[0][1]}()")
    elif pack == "Swamp":
        out += [f"{inner}if U32.is_lt(depth, 2):", f"{inner}  layout.roster.{br[0][1]}()", f"{inner}else:",
                f"{inner}  if U32.is_eq(depth, 2):", f"{inner}    layout.roster.{br[1][1]}()", f"{inner}  else:", f"{inner}    layout.roster.{br[2][1]}()"]
    else:
        out += [f"{inner}if U32.is_lt(depth, 2):", f"{inner}  layout.roster.{br[0][1]}()", f"{inner}else:", f"{inner}  layout.roster.{br[1][1]}()"]
    if not last:
        out.append(f"{ind}else:")
        ind += "  "
out.append("")

# Templates: quadrant rows.
consts = re.findall(r"\nconst (\w+): Template = \[\n(.*?)\n\];", src, re.S)
for name, rows in consts:
    rs = re.findall(r'"([^"]*)"', rows)
    out += [f"def layout.template.{name}() -> List<&2, String>:", "  [" + ", ".join(f'"{r}"' for r in rs) + "]", ""]
out += ["# Each pack's own templates, in Rust's order.",
        "def layout.Pack.templates(+pack: String) -> List<&2, List<&2, String>>:"]
tm = re.search(r"fn templates\(self\).*?match self \{(.*?)\n        \}", src, re.S).group(1)
tarms = re.findall(r"Pack::(\w+) => &\[(.*?)\]", tm)
ind = "  "
for n, (pack, lst) in enumerate(tarms):
    last = n == len(tarms) - 1
    items = ", ".join(f"layout.template.{t.strip()}()" for t in lst.split(","))
    if not last:
        out += [f'{ind}if String.eq(pack, "{snake(pack)}"):', f"{ind}  [{items}]", f"{ind}else:"]
        ind += "  "
    else:
        out.append(f"{ind}[{items}]")
(HERE.parent / "pack_data.bx").write_text("\n".join(out) + "\n")
print("pack_data.bx", len(out), "lines")
