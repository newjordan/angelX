#!/usr/bin/env python3
"""Writes ../layout_consts.bend: the rects and rows other modules own that
layout.rs lays into the home floor and the side-on halls (copied from the Rust)."""
import re, pathlib
HERE = pathlib.Path(__file__).resolve().parent
R = HERE.parents[3] / "crates/delve/src/rules"

def read(n): return (R / n).read_text()

def rect(txt):
    return tuple(int(x) for x in re.findall(r"-?\d+", txt))

def rects(txt):
    return [rect(m) for m in re.findall(r"\(([-\d, ]+)\)", txt)]

def const_rect(src, name):
    m = re.search(r"pub const %s: \(i32, i32, i32, i32\) = \(([-\d, ]+)\);" % name, src)
    return rect(m.group(1))

def const_rects(src, name):
    m = re.search(r"pub const %s: \[\(i32, i32, i32, i32\); \d+\] =\s*\[(.*?)\];" % name, src, re.S)
    return rects(m.group(1))

def rows(src, name, pub=True):
    m = re.search(r"%sconst %s: \[&str; ROWS\] = \[(.*?)\];" % ("pub " if pub else "", name), src, re.S)
    return re.findall(r'"([^"]*)"', m.group(1))

home, fortune, yard, trophies, tavern = read("home.rs"), read("fortune.rs"), read("yard.rs"), read("trophies.rs"), read("tavern.rs")
data = {
    "SPOTS": [rect(m) for m in re.findall(r"furniture: \(([-\d, ]+)\)", home)],
    "BOUNTY_BOARD": [const_rect(home, "BOUNTY_BOARD")],
    "STAIRWELL": [const_rect(home, "STAIRWELL")],
    "STAIR_MOUTH": [const_rect(home, "STAIR_MOUTH")],
    "WHEEL_STAND": [const_rect(fortune, "WHEEL_STAND")],
    "COFFER": [const_rect(fortune, "COFFER")],
    "BENCHES": const_rects(fortune, "BENCHES"),
    "STALL": [const_rect(yard, "STALL")],
    "PLINTHS": [rect(m) for m in re.findall(r"\bat: \(([-\d, ]+)\)", trophies)],
    "BAR": [const_rect(tavern, "BAR")],
    "BOARD": [const_rect(tavern, "BOARD")],
    "STAGE": [const_rect(tavern, "STAGE")],
    "TABLES": const_rects(tavern, "TABLES"),
}
out = ["# generated by _gen/consts.py: constants layout.rs lays that other modules own.",
       "# A rect is (column, row, width, height) in tiles.", ""]
for k, v in data.items():
    out += [f"def layout.{k}() -> List<&2, LayRect>:", "  [" + ", ".join(f"LayRect{{{a}, {b}, {c}, {d}}}" for a, b, c, d in v) + "]", ""]
for name, src, pub, label in (("LEDGE", read("layout.rs"), False, "LEDGE"), ("STAGE", read("outlaw.rs"), True, "OUTLAW_STAGE")):
    rs = rows(src, name, pub)
    out += [f"def layout.{label}() -> List<&2, String>:", "  [" + ", ".join(f'"{r}"' for r in rs) + "]", ""]
(HERE.parent / "layout_consts.bend").write_text("\n".join(out) + "\n")
print({k: len(v) for k, v in data.items()})
