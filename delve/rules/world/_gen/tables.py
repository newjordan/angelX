#!/usr/bin/env python3
"""Writes ../world_tables.bend from the JSON the Rust recorder dumps
(`dump_world_tables` in layout_bend_cases__tests.rs): ROOMS, TRAILS, ENTRANCES."""
import json, os, pathlib, struct, sys
HERE = pathlib.Path(__file__).resolve().parent
if not os.environ.get("DELVE_CASES"):
    sys.exit("set DELVE_CASES to the Bend case directory")
src = pathlib.Path(os.environ["DELVE_CASES"]) / "_tables/world.json"
if not src.exists():
    sys.exit("run the recorder first: " + str(src))
d = json.loads(src.read_text())

def u(v):
    return v & 0xFFFFFFFF

def f(v):
    # the f32 the value is, written with enough digits to round back to it
    x = struct.unpack("<f", struct.pack("<f", v))[0]
    t = repr(x)
    return t if ("." in t or "e" in t) else t + ".0"

def s(v):
    return json.dumps(v)

out = ["# generated by _gen/tables.py from the world's authored tables (rules/world.rs).", ""]
out += ["def world.ROOMS() -> List<&2, WorldRoom>:",
        "  [" + ", ".join(f"WorldRoom{{{s(r['kind'])}, {u(r['cell'][0])}, {u(r['cell'][1])}}}" for r in d["rooms"]) + "]", ""]
out += ["def world.TRAILS() -> List<&2, Sigma<&2, &2, String, _ => String>>:",
        "  [" + ", ".join(f"({s(a)}, {s(b)})" for a, b in d["trails"]) + "]", ""]
es = []
for e in d["entrances"]:
    to = e["to"]
    c, r, w, h = e["at"]
    if "room" in to:
        dest = (to["room"], to["at"][0], to["at"][1], "")
    else:
        dest = ("", 0.0, 0.0, to["delve"])
    es.append(f"WorldEntrance{{{s(e['id'])}, {s(e['room'])}, {u(c)}, {u(r)}, {u(w)}, {u(h)}, {s(dest[0])}, {f(dest[1])}, {f(dest[2])}, {s(dest[3])}, {s(e['label'])}, {s(e['needs'] or '')}}}")
out += ["def world.ENTRANCES() -> List<&2, WorldEntrance>:", "  [" + ", ".join(es) + "]", ""]
(HERE.parent / "world_tables.bend").write_text("\n".join(out))
print(len(d["rooms"]), len(d["trails"]), len(d["entrances"]))
