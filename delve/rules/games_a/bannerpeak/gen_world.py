#!/usr/bin/env python3
"""Bakes crates/delve/assets/bannerpeak/*.map into world_data.bend: the same compose pass
layout::world runs (six sections on one 434 by 64 grid, marks read out and left as air),
and the lists layout::info() reads off the marks. Run from anywhere:
    python3 delve/rules/games_a/bannerpeak/gen_world.py
"""
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
ASSETS = HERE.parents[3] / "crates/delve/assets/bannerpeak"
TILE = 16
# (name, ox, oy, w, h)
SECS = [("hub", 0, 32, 80, 30), ("marsh", 80, 36, 105, 28), ("mill", 185, 36, 88, 18),
        ("shaft", 273, 16, 14, 38), ("snow", 287, 12, 105, 14), ("summit", 392, 10, 42, 14)]
WIDTH, HEIGHT = 434, 64
GLYPH = {'.': 0, ' ': 0, '#': 1, '%': 2, '=': 3, '?': 4, 'L': 5, 'M': 25, 'B': 7, 'X': 8,
         '~': 9, '^': 10, 'H': 11, 'd': 12, 'D': 13}


def compose():
    tiles = [0] * (WIDTH * HEIGHT)
    marks = []
    for name, ox, oy, _, _ in SECS:
        rows = (ASSETS / f"{name}.map").read_text().splitlines()
        for y, row in enumerate(rows):
            for x, c in enumerate(row):
                cx, cy = ox + x, oy + y
                if cx < 0 or cy < 0 or cx >= WIDTH or cy >= HEIGHT:
                    continue
                if c in GLYPH:
                    if c == ' ':
                        continue
                    tiles[cy * WIDTH + cx] = GLYPH[c]
                else:
                    marks.append((c, cx, cy))
    marks.sort(key=lambda m: (m[2], m[1]))  # stable, like sort_by_key
    return tiles, marks


def section_of(x):
    s = 0
    for i, (_, ox, *_r) in enumerate(SECS):
        if x >= ox:
            s = i
    return s


def runs_of(row):
    out, x = [], 0
    while x < WIDTH:
        c = row[x]
        if c == 0:
            x += 1
            continue
        n = 1
        while x + n < WIDTH and row[x + n] == c:
            n += 1
        out += [x, c, n]
        x += n
    return out


def lst(xs):
    return "[" + ", ".join(str(x) for x in xs) + "]"


def main():
    tiles, marks = compose()
    out = ["# Generated by gen_world.py from crates/delve/assets/bannerpeak/*.map. Do not edit.",
           "# The composed world (layout::world) as runs per row, and the lists layout::info() reads.",
           ""]
    rows = [runs_of(tiles[y * WIDTH:(y + 1) * WIDTH]) for y in range(HEIGHT)]
    for y, r in enumerate(rows):
        out.append(f"def bannerpeak.layout.row_{y}() -> List<&2, U32>:\n  {lst(r)}\n")

    # a balanced decision tree over the row number: only the chosen row is built
    def tree(lo, hi):
        if hi - lo == 1:
            return f"bannerpeak.layout.row_{lo}()"
        mid = (lo + hi) // 2
        return f"bannerpeak.u.ife(List<&2, U32>, U32.is_lt(ty, {mid}), _ => {tree(lo, mid)}, _ => {tree(mid, hi)})"
    out.append("def bannerpeak.layout.row(+ty: U32) -> List<&2, U32>:")
    out.append("  " + tree(0, HEIGHT))
    out.append("")

    def pairs(ms):
        return [(m[1], m[2]) for m in ms]

    def of(k):
        return [m for m in marks if m[0] == k]
    one = lambda k: pairs(of(k))[0]
    gates = pairs(of('K'))
    gates.sort(key=lambda p: (section_of(p[0]), -p[1] if SECS[section_of(p[0])][1] == 273 else p[0]))
    sparks = pairs(of('*'))
    sparks.sort(key=lambda p: (section_of(p[0]), -p[1] if SECS[section_of(p[0])][1] == 273 else p[0]))
    coins = pairs(of('$'))
    banners = [None] * 8
    for k, x, y in marks:
        if k.isdigit() and int(k) < 8:
            banners[int(k)] = (x, y)
    foes = [(ord(k), x, y) for k, x, y in marks if k in "scwef"]
    hints = [(ord(k), x, y) for k, x, y in marks if k in '&|/"<>']

    def flat(ps):
        return [v for p in ps for v in p]
    out.append("# Marks as the lists layout::info() keeps, flattened: x, y pairs (foes and hints: glyph, x, y).")
    for name, ps in (("gates", gates), ("sparks", sparks), ("coins", coins)):
        out.append(f"def bannerpeak.layout.info.{name}() -> List<&2, U32>:\n  {lst(flat(ps))}\n")
    out.append(f"def bannerpeak.layout.info.foes() -> List<&2, U32>:\n  {lst(flat(foes))}\n")
    out.append(f"def bannerpeak.layout.info.hints() -> List<&2, U32>:\n  {lst(flat(hints))}\n")
    out.append("# Banner pickups by banner number: x, y, 1 when it has a place, else 0, 0, 0.")
    out.append(f"def bannerpeak.layout.info.banners() -> List<&2, U32>:\n  {lst([v for b in banners for v in ((b[0], b[1], 1) if b else (0, 0, 0))])}\n")
    for name, k in (("start", 'S'), ("pole", 'G'), ("great_pole", 'P'), ("finale", 'F'), ("arch", 'E'),
                    ("board", 'Y'), ("cinder", 'C')):
        x, y = one(k)
        out.append(f"def bannerpeak.layout.info.{name}_x() -> U32:\n  {x}\n")
        out.append(f"def bannerpeak.layout.info.{name}_y() -> U32:\n  {y}\n")
    out.append(f"def bannerpeak.layout.info.gates_len() -> U32:\n  {len(gates)}\n")
    out.append(f"def bannerpeak.layout.info.sparks_len() -> U32:\n  {len(sparks)}\n")
    out.append(f"def bannerpeak.layout.info.coins_len() -> U32:\n  {len(coins)}\n")
    out.append(f"def bannerpeak.layout.info.foes_len() -> U32:\n  {len(foes)}\n")
    (HERE / "world_data.bend").write_text("\n".join(out))
    print("rows", sum(len(r) // 3 for r in rows), "runs;", len(marks), "marks;", len(gates), "gates", len(sparks), "sparks",
          len(coins), "coins", len(foes), "foes", len(hints), "hints")


main()
