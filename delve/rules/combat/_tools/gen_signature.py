#!/usr/bin/env python3
"""patterns::signature (a match over (kind, pack, elite)) -> Bend, arms in order.

Writes patterns.signature(+kind: String, +pack: String, +elite: Bool) -> J.Val:
null for None, else {"every", "damage", "chain": [[emitter, shot], ...]}.
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
from gen_tables import split_top, snake, SRC  # noqa

text = (SRC / "rules/patterns.rs").read_text()
m = re.search(r"pub fn signature\(.*?\{\s*use Emitter::\*;.*?match \(kind, pack, elite\) \{(.*?)\n    \}\n\}", text, re.S)
body = re.sub(r"//.*", "", m.group(1))
arms = [a.strip() for a in split_top(body) if a.strip()]
out = ["# GENERATED by _tools/gen_signature.py from rules/patterns.rs -- do not edit.", ""]
n = len(arms)
for i, arm in enumerate(arms):
    pat, val = arm.split("=>", 1)
    parts = [p.strip() for p in pat.strip()[1:-1].split(",")] if pat.strip() != "_" else ["_", "_", "_"]
    conds = []
    kind, pack, elite = parts
    if kind != "_":
        conds.append('String.eq(k, "%s")' % snake(kind.split("::")[1]))
    if pack != "_":
        conds.append('String.eq(p, "%s")' % snake(pack.split("::")[1]))
    if elite != "_":
        conds.append("e" if elite == "true" else "Bool.not(e)")
    cond = "True{}"
    if conds:
        cond = conds[0]
        for c in conds[1:]:
            cond = "Bool.and(%s, %s)" % (cond, c)
    val = val.strip()
    if val == "None":
        lit = "J.JNull{}"
    else:
        mm = re.match(r"sig\(\s*(\d+),\s*(\d+),\s*&\[(.*)\],?\s*\)$", val, re.S)
        every, damage, chain = mm.group(1), mm.group(2), mm.group(3)
        pairs = re.findall(r"\((\w+),\s*(\w+)\)", chain)
        ch = ",".join('[\\"%s\\",\\"%s\\"]' % (snake(a), snake(b)) for a, b in pairs)
        lit = 'cb.lit("{\\"every\\":%s,\\"damage\\":%s,\\"chain\\":[%s]}")' % (every, damage, ch)
    nxt = "patterns.signature.a%d(k, p, e)" % (i + 1) if i + 1 < n else "J.JNull{}"
    out.append("def patterns.signature.a%d(+k: String, +p: String, +e: Bool) -> J.Val:\n  patterns.signature.if%d(%s, k, p, e)\n" % (i, i, cond))
    out.append("def patterns.signature.if%d(hit: Bool, +k: String, +p: String, +e: Bool) -> J.Val:\n  match hit:\n    case True{}:\n      %s\n    case False{}:\n      %s\n" % (i, lit, nxt))
out.append("def patterns.signature(+kind: String, +pack: String, +elite: Bool) -> J.Val:\n  patterns.signature.a0(kind, pack, elite)\n")
print("\n".join(out))
