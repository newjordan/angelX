#!/usr/bin/env python3
"""Pack the Weapon builder's library into the two files the Creator embeds.

Reads kwpixel's weapon parts (library-v2/weapon_*/w5w.*) and its assembled weapons
(army/arms/weapons/*/weapon.json) and writes:
  crates/delve/assets/creator/weapons/weapons.json   part metadata + library recipes
  crates/delve/assets/creator/weapons/parts.png       every part at native size, shelf-packed

Pillow only. Joint and anchor positions are stored in native px, (master - 2) / 5, exactly as
army/arms/tools/assemble.py reads them.
"""
import json
import sys
from pathlib import Path
from PIL import Image

KW = Path(sys.argv[1] if len(sys.argv) > 1 else '/work/artifacts/kwpixel')
OUT = Path(__file__).resolve().parents[2] / 'crates/delve/assets/creator/weapons'
D = 5


def native(j):
    if j is None:
        return None
    return {'pos': [(j['pos'][0] - 2) // D, (j['pos'][1] - 2) // D], 'class': j.get('class')}


parts = []
images = []
for meta_path in sorted((KW / 'library-v2').glob('weapon_*/w5w.*/part.json')):
    meta = json.loads(meta_path.read_text())
    folder = meta_path.parent
    master = Image.open(folder / 'master.png').convert('RGBA')
    im = master.resize((master.width // D, master.height // D), Image.Resampling.NEAREST)
    anchors = {k: [(v['pos'][0] - 2) // D, (v['pos'][1] - 2) // D] for k, v in (meta.get('anchors') or {}).items()}
    prox = native(meta.get('proximal'))
    dist = native(meta.get('distal'))
    parts.append({
        'id': meta['id'],
        'family': meta['family'],
        'slot': meta['weapon_slot'],
        'class': meta['weapon_class'],
        'prox': prox,
        'dist': dist,
        'anchors': anchors,
        'mass': meta['mass'],
        'stat': meta.get('stat', {}),
        'abilities': meta.get('abilities', []),
        'materials': meta.get('materials', []),
        'tags': meta.get('tags', []),
        'size': [im.width, im.height],
        # First and last opaque columns: the tip and the reach are measured on these.
        'alpha_cols': [im.getchannel('A').getbbox()[0], im.getchannel('A').getbbox()[2] - 1],
    })
    images.append(im)

# Shelf pack, widest shelf 256 px.
shelf_w = 256
x = y = row_h = 0
for p, im in zip(parts, images):
    if x + im.width > shelf_w:
        x, y, row_h = 0, y + row_h + 1, 0
    p['rect'] = [x, y, im.width, im.height]
    x += im.width + 1
    row_h = max(row_h, im.height)
atlas = Image.new('RGBA', (shelf_w, y + row_h), (0, 0, 0, 0))
for p, im in zip(parts, images):
    atlas.paste(im, tuple(p['rect'][:2]))
atlas.save(OUT / 'parts.png', optimize=True)

weapons = []
for wp in sorted((KW / 'army/arms/weapons').glob('*/weapon.json')):
    w = json.loads(wp.read_text())
    keep = ['id', 'name', 'weapon_class', 'hold', 'parts', 'joints', 'gems', 'grip', 'grip2', 'plug', 'tip',
            'cast_anchor', 'extra_anchors', 'stats', 'abilities', 'spells', 'school', 'tags', 'carry_deg']
    weapons.append({k: w[k] for k in keep if k in w})

ramps = json.loads((KW / 'ramps/authoring.json').read_text())['ramps']
data = {
    'schema': 'kwpixel.weapon-kit/1',
    'note': 'Generated by scripts/creator/build-weapon-data.py from the kwpixel weapon library.',
    'ramps': ramps,
    'parts': parts,
    'weapons': weapons,
}
(OUT / 'weapons.json').write_text(json.dumps(data, separators=(',', ':')) + '\n')
print(len(parts), 'parts,', len(weapons), 'weapons; atlas', atlas.size)
