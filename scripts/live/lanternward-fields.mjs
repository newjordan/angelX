// Lanternward's records, as the Bend rules hold them: the word layout of each
// one is the table below. This writes the things that must agree with it: the
// accessor files (a name for every field, over eight-word leaves and eight-leaf
// trees, since Bend has neither field access nor record update) and the layout
// block of `index.js` (which packs the session's JSON into those words and
// back). Run it after editing the table or the rules:
//   node scripts/live/lanternward-fields.mjs
// Only the accessors the rules actually name are written (the rest are dead
// weight in a module that ships under a size cap), so a new use is written by
// naming it and running this again.
