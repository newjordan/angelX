// The words a family is imported as in the other files, by module.
export const ALIASES = ['K', 'F', 'B', 'W', 'Seat', 'Foe', 'Wd', 'Sc', ...Object.keys(W8types)]

const L = 'abcdefgh'
// The file each alias is written to: short, because every call in the compiled
// leg carries its file's name.
const FILE = alias => ({ Seat: 'se', Foe: 'fe', rec: 'r', world: 'w' })[alias] || alias.toLowerCase()
const HEAD = '# Generated by scripts/live/lanternward-fields.mjs from its layout table; edit\n# the table and regenerate, do not edit by hand.\n'

export function files(used) {
  const out = {}
  const need = new Set()
  const LET = 'abcdefgh'
  const pat = (i, keep) => LET.split('').map((c, j) => (j === i ? keep : '_')).join(', ')
  const rebuild = (i, nv) => LET.split('').map((c, j) => (j === i ? nv : c)).join(', ')
  const holes = i => LET.split('').map((c, j) => (j === i ? '_' : c)).join(', ')
  const names = worldFields.map(([n]) => n)
  const ty = t => t.replace(/\b(T8|W8)\b/g, 'R.$1')
  const head = (what, imports) => `${HEAD}#\n# ${what}\nimport Base\n${imports.map(i => `import ./${i[0]}.bend as ${i[1]}\n`).join('')}\n`
  // The world record's own fields and its scalars, as W.name and W.set_name.
  let scalars = ''
  const useField = (n, set) => used.has(`W.${set ? 'set_' : ''}${n}`) || used.has(`#W.${set ? 'set_' : ''}${n}`)
  const want = (alias, name) => used.has(`${alias}.${name}`)
  const pushNeed = (...xs) => xs.forEach(x => need.add(x))
  const sc = T8types.Sc[3]
  sc.forEach((f, n) => {
    const a = n >> 3, b = n & 7
    if (want('W', f)) { scalars += `def ${f}(+w: R.W) -> U32: R.W8.g${b}(R.T8.g${a}(s(w)))\n`; used.add('#W.s'); pushNeed(`W8.g${b}`, `T8.g${a}`) }
    if (want('W', `set_${f}`)) { scalars += `def set_${f}(+w: R.W, v: U32) -> R.W: set_s(w, R.T8.s${a}(s(w), R.W8.s${b}(R.T8.g${a}(s(w)), v)))\n`; used.add('#W.s'); used.add('#W.set_s'); pushNeed(`W8.s${b}`, `T8.s${a}`, `T8.g${a}`, `W8.g${b}`) }
  })
  // T8 families: the family file, and the wrapper over the world's current one.
  for (const [T, [pre, field, direct, fields]] of Object.entries(T8types)) {
    if (T === 'Sc') continue
    if (fields.length > 64) throw Error(`${T} is too wide`)
    if (new Set(fields).size !== fields.length) throw Error(`${T} repeats a field`)
    let gen = head(`${T} fields, by word.`, [[FILE('rec'), 'R']])
    let wrap = head(`${T} fields of the world's ${field}.`, direct ? [[FILE('rec'), 'R'], [FILE('world'), 'W']] : [[FILE('rec'), 'R'], [FILE(T), T], [FILE('world'), 'W']])
    fields.forEach((f, n) => {
      const a = n >> 3, b = n & 7
      const g = `${T}.${f}`, s = `${T}.set_${f}`, wg = `${pre}.${f}`, ws = `${pre}.set_${f}`
      if (direct) {
        if (used.has(wg)) { wrap += `def ${f}(+w: R.W) -> U32: R.W8.g${b}(R.T8.g${a}(W.${field}(w)))\n`; pushNeed(`W8.g${b}`, `T8.g${a}`); used.add(`#W.${field}`) }
        if (used.has(ws)) { wrap += `def set_${f}(+w: R.W, v: U32) -> R.W: W.set_${field}(w, R.T8.s${a}(W.${field}(w), R.W8.s${b}(R.T8.g${a}(W.${field}(w)), v)))\n`; pushNeed(`W8.s${b}`, `T8.s${a}`, `T8.g${a}`, `W8.g${b}`); used.add(`#W.${field}`); used.add(`#W.set_${field}`) }
        return
      }
      if (used.has(g) || used.has(wg)) { gen += `def ${f}(+k: R.T8) -> U32: R.W8.g${b}(R.T8.g${a}(k))\n`; pushNeed(`W8.g${b}`, `T8.g${a}`) }
      if (used.has(s) || used.has(ws)) { gen += `def set_${f}(+k: R.T8, v: U32) -> R.T8: R.T8.s${a}(k, R.W8.s${b}(R.T8.g${a}(k), v))\n`; pushNeed(`W8.s${b}`, `T8.s${a}`, `T8.g${a}`) }
      if (used.has(wg)) { wrap += `def ${f}(+w: R.W) -> U32: ${T}.${f}(W.${field}(w))\n`; used.add(g); used.add(`#W.${field}`) }
      if (used.has(ws)) { wrap += `def set_${f}(+w: R.W, v: U32) -> R.W: W.set_${field}(w, ${T}.set_${f}(W.${field}(w), v))\n`; used.add(s); used.add(`#W.${field}`); used.add(`#W.set_${field}`) }
    })
    if (!direct) out[`${FILE(T)}.bend`] = gen
    out[`${FILE(pre)}.bend`] = wrap
  }
  // The world's fields are written now that the wrappers have said which they need.
  let world = head("The world record's fields and its scalars, as W.name and W.set_name.", [[FILE('rec'), 'R']])
  for (const [n, t] of worldFields) {
    if (useField(n, false)) world += `def ${n}(+w: R.W) -> ${ty(t)}:\n  match w:\n    case R.W{${names.map(m => (m === n ? m : '_')).join(', ')}}:\n      ${n}\n\n`
    if (useField(n, true)) world += `def set_${n}(w: R.W, v: ${ty(t)}) -> R.W:\n  match w:\n    case R.W{${names.map(m => (m === n ? '_' : m)).join(', ')}}:\n      R.W{${names.map(m => (m === n ? 'v' : m)).join(', ')}}\n\n`
  }
  out[`${FILE('world')}.bend`] = world + scalars
  // W8 families.
  for (const [A, fields] of Object.entries(W8types)) {
    let gen = head(`${A} fields, by word.`, [[FILE('rec'), 'R']])
    fields.forEach((f, n) => {
      if (want(A, f)) { gen += `def ${f}(+p: R.W8) -> U32: R.W8.g${n}(p)\n`; pushNeed(`W8.g${n}`) }
      if (want(A, `set_${f}`)) { gen += `def set_${f}(p: R.W8, v: U32) -> R.W8: R.W8.s${n}(p, v)\n`; pushNeed(`W8.s${n}`) }
    })
    out[`${FILE(A)}.bend`] = gen
  }
  // The leaves and trees, and the world they are threaded through.
  let rec = head('The records the rules hold: eight-word leaves (W8) and eight-leaf trees (T8), so a\n# record of up to 64 words is two hops to read and two small objects to write, and\n# the world they are threaded through.', [])
  rec += `type W8 is Data:\n  W8{a: U32, b: U32, c: U32, d: U32, e: U32, f: U32, g: U32, h: U32}\n\ntype T8 is Data:\n  T8{a: W8, b: W8, c: W8, d: W8, e: W8, f: W8, g: W8, h: W8}\n\n`
  for (let i = 0; i < 8; i++) {
    if (need.has(`W8.g${i}`)) rec += `def W8.g${i}(+w: W8) -> U32:\n  match w:\n    case W8{${pat(i, LET[i])}}:\n      ${LET[i]}\n\n`
    if (need.has(`W8.s${i}`)) rec += `def W8.s${i}(w: W8, v: U32) -> W8:\n  match w:\n    case W8{${holes(i)}}:\n      W8{${rebuild(i, 'v')}}\n\n`
  }
  for (let i = 0; i < 8; i++) {
    if (need.has(`T8.g${i}`)) rec += `def T8.g${i}(+t: T8) -> W8:\n  match t:\n    case T8{${pat(i, LET[i])}}:\n      ${LET[i]}\n\n`
    if (need.has(`T8.s${i}`)) rec += `def T8.s${i}(t: T8, v: W8) -> T8:\n  match t:\n    case T8{${holes(i)}}:\n      T8{${rebuild(i, 'v')}}\n\n`
  }
  rec += `type W is Data:\n  W{${worldFields.map(([n, t]) => `${n}: ${t}`).join(', ')}}\n`
  out[`${FILE('rec')}.bend`] = rec
  return out
}

// Every `Alias.name` the hand-written sources mention.
export function usage(dir, generated) {
  const used = new Set()
  const re = new RegExp(`\\b(${ALIASES.join('|')})\\.([a-z_0-9]+)\\b`, 'g')
  for (const f of fs.readdirSync(dir)) {
    if (!f.endsWith('.bend') || generated.has(f)) continue
    const text = fs.readFileSync(path.join(dir, f), 'utf8')
    for (const m of text.matchAll(re)) used.add(`${m[1]}.${m[2]}`)
  }
  return used
}

// The adapter's names for the families.
const JS = { Wd: 'Warden', Pr: 'Prop', Dr: 'Drop', Fu: 'Fuse', Bo: 'Bolt', Ke: 'Kept', St: 'Strike' }
export function slots() {
  const out = {}
  for (const [T, [, , , fields]] of Object.entries(T8types)) out[JS[T] || T] = Object.fromEntries(fields.map((f, i) => [f, i]))
  for (const [T, fields] of Object.entries(W8types)) out[JS[T] || T] = Object.fromEntries(fields.map((f, i) => [f, i]))
  return out
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..', 'cockpit', 'live', 'lanternward-rules')
  const generated = new Set([`${FILE('rec')}.bend`, `${FILE('world')}.bend`, ...Object.entries(T8types).filter(([, v]) => !v[2]).map(([T]) => `${FILE(T)}.bend`), ...Object.values(T8types).map(([pre]) => `${FILE(pre)}.bend`), ...Object.keys(W8types).map(A => `${FILE(A)}.bend`)])
  const used = usage(dir, generated)
  const out = files(used)
  for (const name of generated) {
    const file = path.join(dir, name)
    if (out[name] !== undefined && /\ndef /.test(out[name])) fs.writeFileSync(file, out[name])
    else fs.rmSync(file, { force: true })
  }
  const file = path.join(dir, 'index.js')
  const text = fs.readFileSync(file, 'utf8')
  const begin = '// layout:begin\n'
  const end = '// layout:end\n'
  const a = text.indexOf(begin)
  const b = text.indexOf(end)
  if (a >= 0 && b > a) fs.writeFileSync(file, text.slice(0, a) + `${begin}const SLOT = ${JSON.stringify(slots())}\n${end}` + text.slice(b + end.length))
}
