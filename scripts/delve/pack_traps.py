#!/usr/bin/env python3
"""Cut the Demonic Dungeon floor spikes (VEXED, CC BY 4.0) into the Delve's ink rows.

    python3 scripts/delve/pack_traps.py

Reads `cockpit/assets/dungeon/packs/demonic-dungeon/Generics.png`, whose
spikes are 8x8 frames (a hole, a tip in it, the spike up) in several
colours, and writes `crates/delve/src/render/overworld/arena/pack_traps_frames.rs`:
the grey set for the teal rooms, the orange for the cave, the red for the red.
"""
import sys
from pathlib import Path

from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))
from pack_tiles import ROOT, ink_table  # noqa: E402

SHEET = ROOT / "cockpit/assets/dungeon/packs/demonic-dungeon/Generics.png"
OUT = ROOT / "crates/delve/src/render/overworld/arena/pack_traps_frames.rs"
# Style: the sheet row of its spikes (8 px rows); frames by column from x 64.
SETS = {"GREY": 0, "ORANGE": 4, "RED": 8}
FRAMES = {"HOLE": 0, "TIP": 2, "UP": 4}


def main():
    table = ink_table()
    s = (ROOT / "crates/delve/src/render/overworld/ink.rs").read_text()
    import re

    i = s.index("pub fn ink(ch: char) -> Option<Rgb> {")
    chars = {}
    for cs, h in re.findall(r"((?:'.'\s*\|\s*)*'.')\s*=>\s*0x([0-9a-fA-F]{6})", s[i : s.index("\n}\n", i)]):
        for c in re.findall(r"'(.)'", cs):
            chars.setdefault(tuple(int(h[k : k + 2], 16) for k in (0, 2, 4)), c)
    im = Image.open(SHEET).convert("RGBA")
    out = [
        "// Generated by scripts/delve/pack_traps.py from the Demonic Dungeon",
        "// spikes (VEXED, CC BY 4.0; cockpit/assets/dungeon/LICENSES.md). Do not edit.",
        "",
    ]
    for style, row in SETS.items():
        for frame, col in FRAMES.items():
            out.append(f"pub(super) const {style}_{frame}: [&str; 8] = [")
            for y in range(8):
                line = ""
                for x in range(8):
                    r, g, b, a = im.getpixel((64 + col * 8 + x, row * 8 + y))
                    if not a:
                        line += "."
                        continue
                    near = min(table, key=lambda c: sum((p - q) ** 2 for p, q in zip((r, g, b), c)))
                    line += chars[near]
                out.append(f'    "{line}",')
            out.append("];")
    OUT.write_text("\n".join(out) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
