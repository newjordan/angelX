#!/usr/bin/env python3
"""Cut the Demonic Dungeon monsters (VEXED, CC BY 4.0) into the Delve's ink rows.

    python3 scripts/delve/pack_foes.py

Reads `cockpit/assets/dungeon/packs/demonic-dungeon/Monsters.png` and writes
`crates/delve/src/render/overworld/arena/pack_foes_frames.rs`: three frames a
foe, each colour as its nearest ink, trimmed to the box the three frames
share.
"""
import re
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SHEET = ROOT / "cockpit/assets/dungeon/packs/demonic-dungeon/Monsters.png"
INK_RS = ROOT / "crates/delve/src/render/overworld/ink.rs"
OUT = ROOT / "crates/delve/src/render/overworld/arena/pack_foes_frames.rs"

# Foe: (sheet row, first column) of its three frames. Foes whose art carries
# a telegraph or a state (the Spitter's swell, the Hound's crouch, the
# Oathbound's burning visor) keep their own.
FOES = {
    "SKELETON": (0, 4),     # the archer
    "BAT": (0, 8),
    "MIMIC": (1, 8),
    "HEXER": (2, 0),        # the medusa
    "IMP": (2, 8),          # the trident demon
    "SLIME": (3, 4),
    "WARD": (4, 0),         # the green serpent
    "SPIDERLING": (6, 0),
}

def inks() -> dict[str, tuple[int, int, int]]:
    s = INK_RS.read_text()
    i = s.index("pub fn ink(ch: char) -> Option<Rgb> {")
    body = s[i : s.index("\n}\n", i)]
    out = {}
    for chars, h in re.findall(r"((?:'.'\s*\|\s*)*'.')\s*=>\s*0x([0-9a-fA-F]{6})", body):
        for c in re.findall(r"'(.)'", chars):
            out[c] = tuple(int(h[k : k + 2], 16) for k in (0, 2, 4))
    return out


def main() -> None:
    table = inks()
    near = {}

    def ink(rgb):
        if rgb not in near:
            near[rgb] = min(table, key=lambda c: sum((a - b) ** 2 for a, b in zip(rgb, table[c])))
        return near[rgb]

    im = Image.open(SHEET).convert("RGBA")
    out = [
        "// Generated by scripts/delve/pack_foes.py from the Demonic Dungeon",
        "// monsters (VEXED, CC BY 4.0; cockpit/assets/dungeon/LICENSES.md). Do not edit.",
        "",
    ]
    for name, (row, col) in FOES.items():
        cells = [im.crop(((col + f) * 16, row * 16, (col + f) * 16 + 16, row * 16 + 16)) for f in range(3)]
        xs = [x for c in cells for y in range(16) for x in range(16) if c.getpixel((x, y))[3]]
        ys = [y for c in cells for y in range(16) for x in range(16) if c.getpixel((x, y))[3]]
        x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
        out.append(f"pub(super) const {name}: [&[&str]; 3] = [")
        for c in cells:
            out.append("    &[")
            for y in range(y0, y1 + 1):
                line = "".join(
                    ink(c.getpixel((x, y))[:3]) if c.getpixel((x, y))[3] else "." for x in range(x0, x1 + 1)
                )
                out.append(f'        "{line}",')
            out.append("    ],")
        out.append("];")
    OUT.write_text("\n".join(out) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}; colours -> inks: " + " ".join(f"#{r:02X}{g:02X}{b:02X}={c}" for (r, g, b), c in sorted(near.items())))


if __name__ == "__main__":
    main()
