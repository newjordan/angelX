from collections import deque
from pathlib import Path
phrases=['most recent','right now','as of today','up to date','up-to-date','this week','this month','current events','current news','current version','latest version','web search','search the web','look up','on x','x.com','twitter']
words=['latest','recent','trending','viral','breaking','news','online','internet','live']
nodes=[({},0,0)]
for typ,seq in enumerate((phrases,words)):
 for s in seq:
  n=0
  for b in s.encode():
   if b not in nodes[n][0]:nodes[n][0][b]=len(nodes);nodes.append(({},0,0))
   n=nodes[n][0][b]
  edge,flag,length=nodes[n];nodes[n]=(edge,flag|(typ==0),max(length,len(s) if typ else 0))
assert len(nodes)<256
rows=[[0]*128 for n in nodes]
for i,(edges,_,_) in enumerate(nodes):
 for b,c in edges.items():rows[i][b]=c
fail=[0]*len(nodes);q=deque(nodes[0][0].values())
while q:
 n=q.popleft();f=fail[n];edge,flag,length=nodes[n];nodes[n]=(edge,flag|nodes[f][1],max(length,nodes[f][2]))
 for b in range(128):
  c=rows[n][b]
  if c:fail[c]=rows[f][b];q.append(c)
  else:rows[n][b]=rows[f][b]
out=['/* generated by generate_moa_router.py */','static const unsigned char live_next[][128] = {']
out.extend(' {'+','.join(map(str,row))+'},' for row in rows);out.append('};')
out.append('static const unsigned short live_out[] = {'+','.join(str(flag|(length<<1)) for _,flag,length in nodes)+'};')
table = "\n".join(out) + "\n"
source = Path(__file__).with_name("moa_router.c")
start = "/* BEGIN GENERATED LIVE DFA */\n"
end = "/* END GENERATED LIVE DFA */"
text = source.read_text(encoding="utf-8")
old = text.split(start, 1)[1].split(end, 1)[0]
if "--check" in __import__("sys").argv:
    if old != table:
        raise SystemExit("MoA routing DFA is stale")
else:
    source.write_text(text.replace(start + old + end, start + table + end), encoding="utf-8")
