"""Exports in forms delve can use as-is.

* ink rows (JSON and a generated .rs): every frame is `&[&str]` in delve's own ink
  chars, so `Img::from_rows(&FRAMES[i])` draws it; `flip_h()` gives the left-facing
  frame (the game already does this for its across views).
* sprite sheets: native 1x PNG (game scale) and a 4x preview, facing right and left.
* GIFs on a dungeon backdrop, nearest-upscaled so pixels stay square.
* braille text in the Dotmax manner (2x4 dots a cell, one colour a cell), plain and
  ANSI truecolour, for terminal previews.
"""
import json, os
import numpy as np
from PIL import Image, ImageDraw
from .cutout import Renderer, render_anim
from ..anim import ANIMS, DEFAULT_SET

BG, STONE, FLOOR = (21, 22, 20), (37, 20, 11), (61, 58, 54)


def render_all(ch, anims, scale=1, mode="pixel"):
    r = Renderer(ch, scale=scale, mode=mode)
    out = {a: render_anim(r, a) for a in anims}
    # one canvas for every motion, feet on the same row (game anchor)
    m = np.zeros((r.H, r.W), bool)
    for fr, _, _ in out.values():
        for f in fr:
            m |= f > 0
    ys, xs = np.nonzero(m)
    box = (xs.min(), ys.min(), xs.max() + 1, ys.max() + 1)
    x0, y0, x1, y1 = box
    out = {a: ([f[y0:y1, x0:x1] for f in fr], fps, lp) for a, (fr, fps, lp) in out.items()}
    feet = (r.pad + ch.pivots["hip"][0] * scale - x0, r.pad + ch.h * scale - y0)
    return r, out, feet


def rgba(r, pal, idx, flip=False):
    lut = np.zeros((len(r.inks), 4), np.uint8)
    for i, c in enumerate(r.inks[1:], 1):
        lut[i] = (*pal[c], 255)
    im = lut[idx]
    return im[:, ::-1] if flip else im


def sheet(frames, path, k=1):
    h, w = frames[0].shape[:2]
    im = Image.fromarray(np.concatenate(frames, 1), "RGBA")
    if k > 1:
        im = im.resize((im.width * k, im.height * k), Image.NEAREST)
    im.save(path)


def backdrop(w, h, ground):
    im = np.zeros((h, w, 3), np.uint8)
    im[:] = BG
    yy, xx = np.mgrid[0:h, 0:w]
    brick = ((yy // 4) % 2 * 4 + xx) % 8 == 0
    im[(yy % 4 == 0) | brick] = STONE
    im[ground:] = FLOOR
    im[ground] = (81, 83, 73)
    return im


def on_stage(frame, feet_y, pad=3):
    h, w = frame.shape[:2]
    W, H = w + 2 * pad, h + pad + 2
    bg = backdrop(W, H, pad + feet_y)
    a = frame[..., 3:] > 0
    bg[pad:pad + h, pad:pad + w] = np.where(a, frame[..., :3], bg[pad:pad + h, pad:pad + w])
    return bg


def gif(images, path, fps, k=6, labels=None):
    ims = []
    for i, im in enumerate(images):
        p = Image.fromarray(im).resize((im.shape[1] * k, im.shape[0] * k), Image.NEAREST)
        if labels:
            d = ImageDraw.Draw(p)
            d.text((4, 2), labels[i], fill=(236, 182, 74))
        ims.append(p.convert("P", palette=Image.ADAPTIVE, colors=64))
    ims[0].save(path, save_all=True, append_images=ims[1:], duration=int(1000 / fps), loop=0,
                disposal=2, optimize=False)


def braille(r, pal, idx, colour=True):
    """Dotmax-style: each 2x4 block -> one braille char; the cell takes its
    commonest ink."""
    h, w = idx.shape
    H, W = -(-h // 4) * 4, -(-w // 2) * 2
    g = np.zeros((H, W), np.uint8)
    g[:h, :w] = idx
    bits = [(0, 0, 0x01), (1, 0, 0x02), (2, 0, 0x04), (0, 1, 0x08), (1, 1, 0x10), (2, 1, 0x20),
            (3, 0, 0x40), (3, 1, 0x80)]
    lines = []
    for cy in range(0, H, 4):
        line = []
        for cx in range(0, W, 2):
            blk = g[cy:cy + 4, cx:cx + 2]
            code = sum(b for dy, dx, b in bits if blk[dy, dx])
            ch = chr(0x2800 + code) if code else " "
            if colour and code:
                vals, cnt = np.unique(blk[blk > 0], return_counts=True)
                rr, gg, bb = pal[r.inks[vals[cnt.argmax()]]]
                ch = f"\x1b[38;2;{rr};{gg};{bb}m{ch}"
            line.append(ch)
        lines.append("".join(line) + ("\x1b[0m" if colour else ""))
    return "\n".join(lines)


def rust_module(ch, r, out, feet):
    lines = [f"//! {ch.name}: generated by tools/sprite-rig (spriterig.delve) from {ch.source_ref}.",
             "//! Ink rows facing right; draw with `Img::from_rows(&FRAME)` and `flip_h()` for the left.",
             f"//! Feet anchor (x, y) = ({feet[0]:g}, {feet[1]:g}).", ""]
    for a, (fr, fps, lp) in out.items():
        h = fr[0].shape[0]
        lines.append(f"/// {a}: {len(fr)} frames at {fps} fps{', looping' if lp else ''}.")
        lines.append(f"pub const {a.upper()}: [[&str; {h}]; {len(fr)}] = [")
        for f in fr:
            lines.append("    [" + ", ".join(f'"{s}"' for s in r.to_rows(f)) + "],")
        lines.append("];")
        lines.append(f"pub const {a.upper()}_FPS: u32 = {fps};\n")
    return "\n".join(lines)


def export(ch, pal, outdir, anims=None, gif_k=6, montage=("idle", "walk", "run", "attack_right",
           "jump", "cast", "hurt", "death"), mode="pixel"):
    anims = anims or DEFAULT_SET.split(",")
    os.makedirs(outdir, exist_ok=True)
    r, out, feet = render_all(ch, anims, mode=mode)
    data = {"name": ch.name, "source": ch.source_ref, "note": ch.note, "view": ch.view,
            "facing": "right", "flip_for_left": True,
            "inks": {c: "#%02x%02x%02x" % pal[c] for c in r.inks[1:]},
            "w": int(out[anims[0]][0][0].shape[1]), "h": int(out[anims[0]][0][0].shape[0]),
            "feet": [float(feet[0]), float(feet[1])], "anims": {}}
    mont, labels, mfps = [], [], 12
    for a, (fr, fps, lp) in out.items():
        data["anims"][a] = {"fps": fps, "loop": lp, "frames": [r.to_rows(f) for f in fr]}
        R = [rgba(r, pal, f) for f in fr]
        L = [rgba(r, pal, f, True) for f in fr]
        sheet(R, f"{outdir}/{a}_right.png")
        sheet(L, f"{outdir}/{a}_left.png")
        sheet(R, f"{outdir}/{a}_right_x4.png", 4)
        stage = [on_stage(x, int(feet[1])) for x in R]
        gif(stage, f"{outdir}/{a}.gif", fps, gif_k)
        if a in montage:
            reps = 2 if lp else 1
            for _ in range(reps):
                mont += stage
                labels += [a] * len(stage)
        with open(f"{outdir}/{a}.braille.txt", "w") as fh:
            fh.write("\n\n".join(braille(r, pal, f, False) for f in fr) + "\n")
        with open(f"{outdir}/{a}.braille.ans", "w") as fh:
            fh.write("\n\n".join(braille(r, pal, f, True) for f in fr) + "\n")
    if mont:
        # left-facing half too: a side-scroller turns round
        gif(mont, f"{outdir}/{ch.name}_montage.gif", mfps, gif_k, labels)
    with open(f"{outdir}/{ch.name}.json", "w") as fh:
        json.dump(data, fh)
    with open(f"{outdir}/{ch.name}_frames.rs", "w") as fh:
        fh.write(rust_module(ch, r, out, feet))
    return data


def scroll_demo(chars, pal, path, k=5, W=160):
    """Side-scroll proof: the first character walks right across a scrolling hall,
    turns, runs back left and strikes; the rest of the cast idles along the floor."""
    lead = chars[0]
    r, out, feet = render_all(lead, ["walk", "run", "attack_right", "idle"])
    others = []
    for ch in chars[1:]:
        r2, o2, f2 = render_all(ch, ["idle"])
        others.append((r2, [rgba(r2, pal, f) for f in o2["idle"][0]], f2))
    H = max(f.shape[0] for f in out["walk"][0]) + 14
    ground = H - 6
    plan = [("walk", False, 1.5, 60), ("idle", False, 0, 6), ("run", True, -2.5, 36),
            ("attack_right", True, 0, 10), ("idle", True, 0, 8)]
    x, cam, frames = 20.0, 0.0, []
    t = 0
    for anim, flip, speed, n in plan:
        fr = out[anim][0]
        for i in range(n):
            x += speed
            cam = min(max(0.0, x - W / 2), 400.0)
            bg = backdrop(W, H, ground)
            # parallax pillars every 40 px
            for px in range(-int(cam) % 40 - 40, W, 40):
                bg[2:ground, max(px, 0):max(px + 4, 0)] = (50, 43, 43)
            for j, (r2, idle, f2) in enumerate(others):
                fi = idle[(t + j * 3) % len(idle)]
                sx = int(70 + j * 28 - cam)
                _blit(bg, fi[:, ::-1] if j % 2 else fi, sx, ground - int(f2[1]) + 1)
            im = rgba(r, pal, fr[i % len(fr)], flip)
            _blit(bg, im, int(x - cam), ground - int(feet[1]) + 1)
            frames.append(bg)
            t += 1
    gif(frames, path, 12, k)


def _blit(bg, im, x, y):
    h, w = im.shape[:2]
    H, W = bg.shape[:2]
    x0, y0, x1, y1 = max(x, 0), max(y, 0), min(x + w, W), min(y + h, H)
    if x1 <= x0 or y1 <= y0:
        return
    s = im[y0 - y:y1 - y, x0 - x:x1 - x]
    a = s[..., 3:] > 0
    bg[y0:y1, x0:x1] = np.where(a, s[..., :3], bg[y0:y1, x0:x1])
